#!/usr/bin/env python3
"""Analyze issue edit history exported by fetch-edit-history.ps1 (read-only, local).

For each issue it lists every revision (oldest first) with editor, time, length,
SHA-256 (LF) and damage counts, then marks the first damaged revision and the
last clean revision before it. It also compares the current REST body with the
newest revision and with the repair candidate in kit/candidates/.

Damage signals (REPAIR_GUIDE §1):
  A: '&lt;' / '&gt;' entity escapes
  B: stray '``' outside ```` fences
  F: '_Generated by [Claude Code]' footer

Usage: python3 analyze-edits.py <edits-dir> [--dump <out-dir>]
  --dump writes every revision body as rev-<n>-<idx>.md (LF) for manual diff.
"""
import hashlib
import json
import pathlib
import sys

ISSUES = (9, 74, 75)


def lf(s):
    return s.replace("\r\n", "\n")


def sha(s):
    return hashlib.sha256(lf(s).encode("utf-8")).hexdigest()


def stray_ticks(s):
    return sum(line.count("``") for line in lf(s).split("\n") if not line.startswith("````"))


def damage(s):
    return {
        "lt": s.count("&lt;"),
        "gt": s.count("&gt;"),
        "ticks": stray_ticks(s),
        "footer": s.count("_Generated by [Claude Code]"),
    }


def is_damaged(d):
    return d["lt"] + d["gt"] + d["ticks"] + d["footer"] > 0


def load_pages(path):
    """gh --paginate writes one JSON object per page, concatenated."""
    text = path.read_text(encoding="utf-8-sig")
    dec, i, pages = json.JSONDecoder(), 0, []
    while i < len(text):
        while i < len(text) and text[i].isspace():
            i += 1
        if i >= len(text):
            break
        obj, i = dec.raw_decode(text, i)
        pages.append(obj)
    return pages


def revisions(pages):
    nodes = []
    for p in pages:
        if p.get("errors"):
            raise SystemExit(f"GraphQL errors: {p['errors']}")
        nodes += p["data"]["repository"]["issue"]["userContentEdits"]["nodes"]
    nodes = [n for n in nodes if n.get("diff") is not None]
    nodes.sort(key=lambda n: (n.get("editedAt") or n.get("createdAt") or ""))
    return nodes


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    src = pathlib.Path(sys.argv[1])
    dump = pathlib.Path(sys.argv[sys.argv.index("--dump") + 1]) if "--dump" in sys.argv else None
    here = pathlib.Path(__file__).resolve().parent
    report = {}
    for n in ISSUES:
        revs = revisions(load_pages(src / f"edits-{n}.json"))
        cur = json.loads((src / f"issue-{n}.json").read_text(encoding="utf-8-sig"))
        body = cur.get("body") or ""
        cand = (here / "kit" / "candidates" / f"issue-{n}.repair-candidate.md").read_text(encoding="utf-8")
        print(f"\n== #{n} updated_at={cur.get('updated_at')} revisions={len(revs)}")
        rows, first_bad = [], None
        for idx, r in enumerate(revs):
            d = damage(r["diff"])
            row = {
                "idx": idx,
                "editedAt": r.get("editedAt"),
                "editor": (r.get("editor") or {}).get("login") or "-",
                "len": len(r["diff"]),
                "sha256_lf": sha(r["diff"]),
                **d,
            }
            rows.append(row)
            if first_bad is None and is_damaged(d):
                first_bad = idx
            print(f"  [{idx:3}] {row['editedAt']} {row['editor']:<20} len={row['len']:6} "
                  f"lt={d['lt']} gt={d['gt']} ticks={d['ticks']} footer={d['footer']} {row['sha256_lf'][:12]}")
            if dump:
                dump.mkdir(parents=True, exist_ok=True)
                (dump / f"rev-{n}-{idx:03}.md").write_bytes(lf(r["diff"]).encode("utf-8"))
        newest = revs[-1]["diff"] if revs else None
        res = {
            "current_updated_at": cur.get("updated_at"),
            "current_sha256_lf": sha(body),
            "current_damage": damage(body),
            "newest_revision_equals_current": newest is not None and lf(newest) == lf(body),
            "candidate_sha256": sha(cand),
            "first_damaged_idx": first_bad,
            "last_clean_idx": (first_bad - 1) if first_bad else None,
            "revisions": rows,
        }
        # A revision that looks like a full body should be close to the body length.
        if newest is not None and not res["newest_revision_equals_current"]:
            print("  NOTE newest revision != current body: 'diff' may not be the full body; use web UI history.")
        if first_bad is not None:
            print(f"  FIRST DAMAGED idx={first_bad} at {rows[first_bad]['editedAt']} by {rows[first_bad]['editor']}")
            if first_bad > 0:
                print(f"  LAST CLEAN    idx={first_bad - 1} at {rows[first_bad - 1]['editedAt']}")
        else:
            print("  no damaged revision found in history")
        report[str(n)] = res
    out = src / "analysis.json"
    out.write_text(json.dumps(report, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
